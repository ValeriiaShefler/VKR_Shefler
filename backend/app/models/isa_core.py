"""
Эталонная модель Международной стандартной атмосферы.
Соответствует ГОСТ Р 70469-2026 (ранее ГОСТ 4401-81) / ISO 2533:2026.

Диапазон: 0–20 000 м (тропосфера + нижняя стратосфера).
"""
import numpy as np


# ---------- Нормативные подписи ----------
STANDARD_NAME = "ГОСТ Р 70469-2026 / ISO 2533:2026"
STANDARD_NAME_LEGACY = "ГОСТ 4401-81 / ISO 2533:1975"
ISO_5878_NAME = "ISO 5878:2026"


def standard_atmosphere(h: float):
    """
    Возвращает (T, P, rho, a) для заданной высоты h (м).
    Диапазон: 0 ≤ h ≤ 20 000 м.

    Параметры:
        h — геометрическая высота, м

    Возвращает:
        T   — температура, К
        P   — давление, Па
        rho — плотность, кг/м³
        a   — скорость звука, м/с
    """
    T0 = 288.15
    P0 = 101325.0
    g = 9.80665
    R = 287.053
    gamma = 1.4

    if h <= 11000:
        # Тропосфера
        T = T0 - 0.0065 * h
        P = P0 * (T / T0) ** (g / (0.0065 * R))
    elif h <= 20000:
        # Стратосфера
        T = 216.65
        _, P11, _, _ = standard_atmosphere(11000)
        P = P11 * np.exp(-g / (R * T) * (h - 11000))
    else:
        raise ValueError("Высота вне диапазона 0..20000 м")

    rho = P / (R * T)
    a = np.sqrt(gamma * R * T)
    return T, P, rho, a